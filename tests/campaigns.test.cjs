const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {PGlite}=require('@electric-sql/pglite');
const admin='00000000-0000-4000-8000-000000000001';
const member='00000000-0000-4000-8000-000000000002';
const other='00000000-0000-4000-8000-000000000003';

test('campanhas protegem administração e recibos e aplicam agenda, prioridade, público e frequência',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema neo_private; create schema auth; create schema storage;
   create table storage.buckets(id text primary key,name text,public boolean,file_size_limit int,allowed_mime_types text[]);
   create table storage.objects(bucket_id text,name text);
   alter table storage.objects enable row level security;
   create table neo_private.community_materials(id uuid primary key,title text);
   create table neo_private.shop_products(id uuid primary key,name text,active boolean);
   create table neo_private.shop_promotions(id uuid primary key,name text,active boolean,restricted_to_user boolean,
    restricted_user_id uuid,kind text,starts_at timestamptz,ends_at timestamptz);
   insert into neo_private.community_materials values ('${other}','Material fictício');
   insert into neo_private.shop_products values ('${other}','Produto fictício',true);
   insert into neo_private.shop_promotions values ('${other}','Oferta fictícia',true,false,null,'percent',null,null);
   insert into storage.objects values ('neo-campaign-images','${admin}/${other}.jpg');
   create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create function public.neo_admin_access() returns boolean language sql as $$select true$$;
   create function public.neo_has_consent(text) returns boolean language sql as $$select auth.uid()<>'${other}'::uuid$$;
   create table auth.users(id uuid primary key,created_at timestamptz default now(),raw_app_meta_data jsonb);
   create table public.neo_profiles(user_id uuid primary key);
   create table public.neo_consents(user_id uuid,purpose text,version text,granted boolean);
   create table neo_private.push_devices(id uuid primary key default gen_random_uuid(),user_id uuid,endpoint text,keys jsonb);
   create table neo_private.admin_members(user_id uuid primary key);
   create table neo_private.community_members(user_id uuid primary key);
   insert into auth.users(id,raw_app_meta_data) values ('${admin}','{}'),('${member}','{"campaign_plan":"plus"}'),('${other}','{}');
   insert into public.neo_consents values ('${member}','terms','2026-11-v1',true);
   insert into neo_private.push_devices(user_id,endpoint,keys) values ('${member}','https://invalid.invalid','{}');
   insert into public.neo_profiles values ('${member}'),('${other}');
   insert into neo_private.admin_members values ('${admin}');`);
  await db.exec(fs.readFileSync('supabase/migrations/20261121195231_admin_campaigns.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/20261121195245_campaign_push.sql','utf8'));
  await db.exec(fs.readFileSync('supabase/migrations/20261121200721_campaign_editor_completion.sql','utf8'));
  const allowed=(path,write=false)=>db.query('select public.neo_campaign_image_allowed($1,$2) value',[path,write]).then(r=>r.rows[0].value);
  const image=admin+'/'+other+'.jpg';
  const as=async id=>{
   await db.exec('reset role');
   await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id||'']);
   await db.exec(id?'set role authenticated':'set role anon');
  };
  const manage=(action,id=null,data={})=>db.query('select public.neo_campaign_admin($1,$2,$3) value',[action,id,JSON.stringify(data)]).then(r=>r.rows[0].value);
  const visit=(action='next',id=null)=>db.query('select public.neo_campaign_visit($1,$2) value',[action,id]).then(r=>r.rows[0].value);
  await as(null);
  await assert.rejects(visit(),{code:'42501'});
  await as(member);
  await assert.rejects(manage('list'),{code:'42501'});
  await assert.rejects(db.query('select * from neo_private.campaigns'),{code:'42501'});
  await as(admin);
  await assert.rejects(manage('save',null,{title:'Inválida',link_url:'//destino.example.invalid'}),{code:'23514'});
  assert.equal(await allowed(image,true),true);
  for(const kind of ['document','product','offer','promotion']){
   assert.equal((await manage('catalog',null,{kind,search:'fictí'}))[0].id,other);
  }
  await assert.rejects(manage('save',null,{title:'Hora inexistente',timezone:'America/New_York',starts_local:'2026-03-08T02:30'}),/inexistente/);
  const scheduled=await manage('save',null,{title:'Horário local',timezone:'America/Sao_Paulo',starts_local:'2026-11-22T09:30'});
  assert.equal(new Date(scheduled.starts_at).toISOString(),'2026-11-22T12:30:00.000Z');
  assert.equal((await manage('list')).find(x=>x.id===scheduled.id).starts_local,'2026-11-22T09:30');
  const pushOnly=await manage('save',null,{title:'Push independente',popup_enabled:false,push_requested:true,audience:'plan',targets:['plus'],priority:50});
  const first=await manage('save',null,{title:'Primeira',audience:'plan',targets:['plus'],priority:10,image_path:image,kind:'product',content_id:other});
  const second=await manage('save',null,{title:'Segunda',audience:'segment',targets:['recent']});
  const future=await manage('save',null,{title:'Futura',starts_at:'2200-01-01T00:00:00Z',priority:99});
  for(const c of [pushOnly,first,future])await manage('activate',c.id);
  assert.equal((await manage('duplicate',first.id)).status,'draft');
  await as(member);
  await assert.rejects(db.query('select public.neo_campaign_push_claim()'),{code:'42501'});
  assert.equal(await visit(),null,'metadata na conta não autoriza plano');
  assert.equal(await allowed(image),false);
  assert.equal(await allowed(image,true),false);
  await assert.rejects(manage('assign_plan',member,{plan:'plus'}),{code:'42501'});
  await as(admin);
  await manage('assign_plan',member,{plan:'plus'});
  await manage('activate',second.id);
  await as(member);
  assert.equal((await db.query('select public.neo_campaign_push_preference(true) enabled')).rows[0].enabled,true);
  await db.exec(`reset role; set request.jwt.claims='{"role":"service_role"}'; set role service_role;`);
  const independent=await db.query('select public.neo_campaign_push_claim() batch');
  assert.equal(independent.rows[0].batch.length,1,'push tem fila antes de qualquer pop-up');
  assert.equal(independent.rows[0].batch[0].kind,'campaign');
  await as(member);
  const offer=await visit();
  assert.equal(offer.title,'Primeira');
  assert.equal(offer.link_url,'/?produto='+other+'#loja');
  assert.equal(await allowed(image),true);
  assert.equal(await visit(),null);
  assert.equal(await visit('clicked',offer.impression),false);
  await as(other);
  assert.equal(await visit(),null);
  assert.equal(await visit('displayed',offer.impression),null);
  assert.equal(await allowed(image),false);
  await as(member);
  assert.equal(await visit('displayed',offer.impression),true);
  assert.equal(await visit('clicked',offer.impression),true);
  assert.equal(await visit('clicked',offer.impression),true);
  await db.exec(`reset role; set request.jwt.claims='{"role":"service_role"}'; set role service_role;`);
  const jobs=await db.query('select public.neo_campaign_push_claim() batch');
  assert.equal(jobs.rows[0].batch.length,0);
  assert.deepEqual((await db.query('select public.neo_campaign_push_claim() batch')).rows[0].batch,[]);
  await as(member);
  assert.equal((await db.query('select public.neo_campaign_push_preference(false) enabled')).rows[0].enabled,false);
  await db.exec("reset role; update neo_private.campaign_impressions set reserved_at=now()-interval '6 minutes'");
  await as(member);
  assert.equal((await visit()).title,'Segunda');
  await as(admin);
  assert.equal((await manage('list')).find(c=>c.id===first.id).clicks,1);
  assert.equal((await manage('pause',second.id)).status,'paused');
  assert.equal((await manage('archive',first.id)).status,'archived');
 }finally{await db.close()}
});
