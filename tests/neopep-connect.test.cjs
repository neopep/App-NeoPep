const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {PGlite}=require('@electric-sql/pglite');
const main='10000000-0000-4000-8000-000000000001';
const backup='10000000-0000-4000-8000-000000000002';
const member='10000000-0000-4000-8000-000000000003';
const group='20000000-0000-4000-8000-000000000001';
const campaign='30000000-0000-4000-8000-000000000001';
const publication=id=>'40000000-0000-4000-8000-00000000000'+id;
const secret=i=>String(i).repeat(64);

test('Connect protege registros, seleciona reservas elegíveis e bloqueia reenvio de resultado incerto',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon;create role authenticated;create schema auth;create schema neo_private;create schema storage;
   create table auth.users(id uuid primary key);
   insert into auth.users values ('${main}'),('${backup}'),('${member}');
   create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create function neo_private.campaign_admin_allowed() returns boolean language sql as $$select auth.uid() in ('${main}','${backup}')$$;
   create table neo_private.campaigns(id uuid primary key,status text,whatsapp_enabled boolean);
   create function neo_private.campaign_display_state(c neo_private.campaigns,t timestamptz) returns text language sql as $$select c.status$$;
   create table neo_private.campaign_wa_groups(id uuid primary key,active boolean);
   create table neo_private.campaign_wa_publications(id uuid primary key,campaign_id uuid,group_id uuid,status text,scheduled_at timestamptz);
   create function public.neo_campaign_wa(text) returns jsonb language sql as $$select '[]'::jsonb$$;
   create table storage.buckets(id text,name text,public boolean,file_size_limit int,allowed_mime_types text[]);
   create table storage.objects(bucket_id text,name text,metadata jsonb);alter table storage.objects enable row level security;
   insert into neo_private.campaigns values ('${campaign}','active',true);
   insert into neo_private.campaign_wa_groups values ('${group}',true);
   insert into neo_private.campaign_wa_publications values
    ('${publication(1)}','${campaign}','${group}','pending',now()-interval '10 minutes'),
    ('${publication(2)}','${campaign}','${group}','pending',now()-interval '5 minutes'),
    ('${publication(3)}','${campaign}','${group}','pending',now()-interval '1 minute'),
    ('${publication(4)}','${campaign}','${group}','pending',now()-interval '30 seconds');`);
  await db.exec(fs.readFileSync('supabase/migrations/20261121233733_neopep_connect.sql','utf8'));
  await db.exec(`insert into neo_private.connect_releases(version,path,sha256,bytes)
   values('0.1.1','0.1.1/NeoPepConnectSetup.exe',repeat('c',64),39936)`);
  const correction=fs.readFileSync('supabase/migrations/20261122003342_neopep_connect_pause_where.sql','utf8');
  assert.match(correction,/update neo_private\.connect_config set paused = \(p_data->>'paused'\)::boolean where singleton = true;/i);
  await db.exec(correction);
  await db.exec(fs.readFileSync('supabase/migrations/20261122015846_neopep_connect_updates.sql','utf8'));
  const as=async(account,role='authenticated')=>{
   await db.exec('reset role');
   await db.query("select set_config('request.jwt.claim.sub',$1,false)",[account||'']);
   await db.exec('set role '+role);
  };
  const query=(q,args)=>db.query(q,args).then(r=>r.rows[0].value);
  const admin=(action,data={})=>query('select public.neo_connect_admin($1,$2) value',[action,JSON.stringify(data)]);
  const device=(action,id,key,data={})=>query('select public.neo_connect_device($1,$2,$3,$4) value',[action,id,key,JSON.stringify(data)]);
  const heartbeat=(computer,account)=>device('heartbeat',computer.id,computer.key,{account,version:'0.1.0',working_set_mb:20});
  const rpc=(computer,action,data)=>device(action,computer.id,computer.key,data);
  const register=async i=>({...await device('register',null,secret(i),{label:'Computador '+i}),key:secret(i)});
  const attempt=task=>({task:task.id,fence:task.fence});
  const update=(action,computer,version=null,outcome=null)=>query(
   'select public.neo_connect_update($1,$2,$3,$4,$5) value',[action,computer.id,computer.key,version,outcome]);
  const release=(action,data={})=>query('select public.neo_connect_update_admin($1,$2) value',[action,JSON.stringify(data)]);
  await as(null,'anon');await assert.rejects(admin('snapshot'),{code:'42501'});
  const allowed=path=>query('select public.neo_connect_release_allowed($1) value',[path]);
  await assert.rejects(allowed('0.1.1/NeoPepConnectSetup.exe'),{code:'42501'});
  await as(member);await assert.rejects(admin('snapshot'),{code:'42501'});
  assert.equal(await allowed('0.1.1/NeoPepConnectSetup.exe'),false);
  await as(main);
  assert.equal(await allowed('0.1.1/NeoPepConnectSetup.exe'),true);
  assert.equal(await allowed('0.1.2/NeoPepConnectSetup.exe'),false);
  const a=await admin('create_account',{identity:'fixture-principal'});
  const first=await register(1),same=await register(3);
  assert.equal((await heartbeat(first,a.id)).state,'pending');
  await assert.rejects(rpc(first,'claim'),{code:'42501'});
  for(const pc of [first,same])await admin('approve',{id:pc.id});
  await admin('priority',{id:first.id,priority:100});
  await admin('associate',{group,account:a.id,verified:true,may_publish:true});
  assert.equal(await update('check',first),null,'legacy manual release stays outside the automatic channel');
  const prepared={version:'0.2.3',artifact:'runner-fixture',sha256:'a'.repeat(64),bytes:42,signature:'A'.repeat(342)+'=='};
  await release('register',prepared);
  assert.equal(await update('check',first),null);
  assert.equal(await allowed('0.2.3/NeoPepConnectSetup.exe'),false);
  await assert.rejects(release('approve',{version:'0.2.3'}),/objeto privado/);
  await db.exec(`reset role;insert into storage.objects values
   ('neo-connect-releases','0.2.3/NeoPepConnectSetup.exe','{"size":42}');`);
  await as(main);await release('approve',{version:'0.2.3',required:true});
  const offered=await update('download',first,'0.2.3');
  assert.equal(offered.required,true);
  assert.equal(offered.profile,'staging');
  assert.equal(offered.artifact,'runner-fixture');
  await update('report',first,'0.2.3','rollback');
  assert.equal((await release('list')).events[0].outcome,'rollback');
  await as(member);await assert.rejects(update('check',first),{code:'42501'});
  await assert.rejects(release('list'),{code:'42501'});
  await as(main);await release('block',{version:'0.2.3'});
  assert.equal(await update('download',first,'0.2.3'),null);
  await heartbeat(first,a.id);await heartbeat(same,a.id);
  assert.deepEqual((await rpc(first,'reminders')).items,[]);
  await as(backup);
  const b=await admin('create_account',{identity:'fixture-reserva'});
  const reserve=await register(2);await admin('approve',{id:reserve.id});await heartbeat(reserve,b.id);
  assert.equal((await admin('snapshot')).devices.some(pc=>'secret_hash' in pc),false);
  await assert.rejects(device('heartbeat',first.id,first.key),{code:'42501'});
  await admin('queue',{id:publication(1),account:a.id,mode:'fallback'});
  assert.equal(await rpc(reserve,'claim'),null,'pausa inicial');
  const originalQueue=(await admin('snapshot')).tasks;
  await admin('pause',{paused:false});
  assert.equal((await admin('snapshot')).paused,false);
  await admin('pause',{paused:true});
  const pausedSnapshot=await admin('snapshot');
  assert.equal(pausedSnapshot.paused,true);
  assert.deepEqual(pausedSnapshot.tasks,originalQueue);
  assert.equal(await rpc(reserve,'claim'),null);
  await admin('pause',{paused:false});
  assert.equal(await rpc(reserve,'claim'),null,'convite não autoriza reserva');
  await admin('associate',{group,account:b.id,verified:true,may_publish:true});
  assert.equal(await rpc(reserve,'claim'),null,'principal está disponível');
  await as(main);const initial=await rpc(first,'claim');
  assert.equal(initial.account,a.id);assert.equal(await rpc(same,'claim'),null);
  await db.exec(`reset role;update neo_private.connect_devices set last_seen=now()-interval '2 minutes' where owner_id='${main}';update neo_private.connect_tasks set lease_until=now()-interval '1 second';`);
  await as(backup);const substituted=await rpc(reserve,'claim');
  assert.equal(substituted.id,initial.id);assert.notEqual(substituted.fence,initial.fence);
  assert.equal(substituted.account,b.id);
  await as(main);await heartbeat(first,a.id);
  await assert.rejects(rpc(first,'start',attempt(initial)),{code:'42501'});
  await as(backup);await rpc(reserve,'start',attempt(substituted));
  await db.exec("reset role;update neo_private.connect_tasks set lease_until=now()-interval '1 second'");
  await as(main);assert.equal(await rpc(first,'claim'),null);
  assert.equal((await admin('snapshot')).tasks[0].state,'uncertain');
  await admin('queue',{id:publication(2),account:a.id,mode:'linked'});
  await heartbeat(same,a.id);
  const linked=await rpc(same,'claim');assert.equal(linked.account,a.id);
  await rpc(same,'start',attempt(linked));await rpc(same,'finish',{...attempt(linked),outcome:'simulated'});
  await admin('queue',{id:publication(3),account:a.id,mode:'linked'});
  assert.equal((await rpc(first,'claim')).account,a.id);
  await admin('revoke',{id:first.id});
  await assert.rejects(heartbeat(first,a.id),{code:'42501'});
  await admin('queue',{id:publication(4),account:a.id,mode:'fixed'});
  await db.exec('reset role;update neo_private.campaign_wa_groups set active=false;');
  await as(main);assert.equal(await rpc(same,'claim'),null);
 }finally{await db.close();}
});
